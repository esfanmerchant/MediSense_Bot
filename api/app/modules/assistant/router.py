"""The patient health assistant (spec §18-21).

Three endpoints, and the boundaries between them are the safety design:

* ``POST /assistant/chat`` answers a question. Grounded in the patient's own
  prescriptions and appointments, validated on the way out, and escalated by a
  deterministic layer the model cannot argue with.
* ``POST /assistant/symptoms`` extracts symptoms from what the patient said —
  typed or transcribed from speech — and hands them back **for correction**. It
  writes nothing.
* ``POST /assistant/symptoms/confirm`` stores the corrected list as
  ``ReportedSymptom`` rows with source ``PATIENT_REPORTED`` or ``AI_ASSISTED``.
* ``POST /assistant/chat/image`` is ``/chat`` with a photographed report or
  prescription attached. The image is read by the model for that one answer
  and **never stored**: it is not a document upload, and a patient who wants
  the report kept uses the documents page, where retention and access are
  governed. Same consent, same validation, same escalation.

That last distinction is spec §21 and conflict C7: a symptom the patient
described is *patient-reported information*, not a physician's finding. It sits
in a staging table with its provenance recorded, and only a doctor's explicit
promotion turns it into a medical record. There is no code path from this module
into ``medical_records``.

Consent gates everything here: the assistant sends the patient's words to an
external provider, which is exactly what AI consent covers (conflict C2).
"""

